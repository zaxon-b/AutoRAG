"""Run body-text retrieval + end-to-end QA for the 70 answerable image cases.

Anchors come from the cached visual-ablation result (route ``rrf_image_1_multimodal_0_6``
= image-weighted 1.0 / multimodal 0.6 RRF Top1), so image retrieval is NOT re-run.
Body retrieval reuses the production text pipeline (BM25/Dense -> RRF -> Cross-Encoder
-> AutoMerge, with icon-group occurrence pages injected). Answers are generated by the
same grounded prompt used in production, with NO first-pass VLM fields leaked in.
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, "/app")

from router.qa_rt import (
    _build_image_answer_question,
    _build_insufficient_text_answer,
    _build_visual_anchor,
)
from service.answer_generation_service import complete_answer
from service.icon_catalog_service import canonicalize_evidence
from service.retrieval_service import retrieve_visual_anchor_text
from utils.database import SessionLocal

ROUTE = "rrf_image_1_multimodal_0_6"
QUERY_TAIL = "含义 亮起 怎么办 处理方法"


def anchor_matches(row: dict, cand: dict) -> bool:
    gold_type = row.get("visual_gold_type")
    if gold_type == "visual_chunk":
        return str(cand.get("chunk_id")) in set(row.get("expected_visual_chunk_ids") or [])
    return str(cand.get("icon_group_id")) in set(row.get("expected_icon_group_ids") or [])


def minimal_vision(text_query: str, title: str) -> dict:
    """Vision dict that deliberately carries NO first-pass VLM content."""
    return {
        "recognized_object": title or "unknown",
        "visual_description": "",
        "ocr_text": "",
        "candidate_names": [],
        "visual_keywords": [],
        "normalized_query": text_query,
        "risk_level": "unknown",
    }


def main() -> None:
    cached_path = Path(sys.argv[1])
    dataset_path = Path(sys.argv[2])
    out_path = Path(sys.argv[3])

    cached = json.loads(cached_path.read_text(encoding="utf-8"))
    records = {
        r["id"]: r
        for r in (json.loads(line) for line in dataset_path.read_text(encoding="utf-8").splitlines() if line.strip())
    }

    rows = [r for r in cached.get("image_rows") or [] if not r.get("should_refuse")]
    db = SessionLocal()
    results = []
    errors = 0
    try:
        for index, row in enumerate(rows, start=1):
            record = records.get(row["id"]) or {}
            started = time.monotonic()
            try:
                candidates = row.get("route_candidates", {}).get(ROUTE) or []
                if not candidates:
                    results.append({"id": row["id"], "status": "no_anchor", "error": "missing route candidates"})
                    continue
                anchor = candidates[0]
                anchor_correct = anchor_matches(row, anchor)

                object_name = str(
                    anchor.get("object_name") or record.get("expected_icon") or ""
                ).strip()
                question = record.get("question") or "这张图片是什么，应该如何理解或使用？"
                text_query = " ".join(
                    part for part in (object_name, QUERY_TAIL) if part
                ) or question

                visual_anchor = _build_visual_anchor(anchor)
                visual_evidence = {**canonicalize_evidence(anchor), "evidence_role": "visual"}

                if not object_name:
                    results.append({
                        "id": row["id"],
                        "status": "no_object_name",
                        "anchor_correct": anchor_correct,
                        "anchor": visual_anchor,
                        "text_query": text_query,
                    })
                    continue

                text_evidence = retrieve_visual_anchor_text(
                    db,
                    record.get("manual_id") or "demo_manual",
                    text_query,
                    visual_anchor,
                    top_k=4,
                )[:4]
                evidence = [visual_evidence, *text_evidence]

                if not text_evidence:
                    answer = _build_insufficient_text_answer(visual_evidence)
                    status = "insufficient_text_evidence"
                else:
                    title = (
                        visual_evidence.get("object_name")
                        or visual_evidence.get("section_title")
                        or object_name
                    )
                    vision = minimal_vision(text_query, title)
                    visual_match = {
                        "object_name": visual_evidence.get("object_name"),
                        "section_title": visual_evidence.get("section_title"),
                        "page": visual_evidence.get("page"),
                        "modality": visual_evidence.get("modality"),
                        "icon_group_id": visual_evidence.get("icon_group_id"),
                    }
                    answer_question = _build_image_answer_question(
                        vision, question, text_query, visual_match
                    )
                    answer = complete_answer(answer_question, evidence)
                    status = "verified"

                results.append({
                    "id": row["id"],
                    "variant": row.get("variant"),
                    "visual_gold_type": row.get("visual_gold_type"),
                    "anchor_correct": anchor_correct,
                    "anchor": {
                        "object_name": anchor.get("object_name"),
                        "section_title": anchor.get("section_title"),
                        "page": anchor.get("page"),
                        "modality": anchor.get("modality"),
                        "icon_group_id": anchor.get("icon_group_id"),
                        "chunk_id": anchor.get("chunk_id"),
                        "rrf_score": anchor.get("rrf_score"),
                        "match_method": anchor.get("match_method"),
                    },
                    "text_query": text_query,
                    "text_evidence": [
                        {
                            "chunk_id": item.get("chunk_id"),
                            "page": item.get("page"),
                            "section_title": item.get("section_title"),
                            "content_text": str(item.get("content_text") or "")[:400],
                            "match_method": item.get("match_method"),
                        }
                        for item in text_evidence
                    ],
                    "answer": answer,
                    "status": status,
                    "elapsed_seconds": round(time.monotonic() - started, 2),
                })
                print(f"[{index}/{len(rows)}] {row['id']} anchor_correct={anchor_correct} status={status} evid={len(text_evidence)}", flush=True)
            except Exception as error:
                errors += 1
                results.append({"id": row["id"], "status": "error", "error": f"{type(error).__name__}: {error}"})
                print(f"[{index}/{len(rows)}] {row['id']} ERROR {error}", flush=True)
    finally:
        db.close()

    summary = {
        "route": ROUTE,
        "count": len(rows),
        "anchor_correct": sum(bool(r.get("anchor_correct")) for r in results),
        "verified": sum(r.get("status") == "verified" for r in results),
        "insufficient_text_evidence": sum(r.get("status") == "insufficient_text_evidence" for r in results),
        "no_object_name": sum(r.get("status") == "no_object_name" for r in results),
        "errors": errors,
        "text_evidence_nonempty": sum(bool(r.get("text_evidence")) for r in results),
    }
    out = {"run": {"mode": "image_weighted_anchor_downstream", "route": ROUTE, "query": QUERY_TAIL}, "summary": summary, "image_rows": results}
    out_path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nSUMMARY", json.dumps(summary, ensure_ascii=False))


if __name__ == "__main__":
    main()
